// La suma del firmware (la misma que comprueba melonDS)
function crc16(b, desde, cuantos, inicio) {
  const tabla = [0xc0c1, 0xc181, 0xc301, 0xc601, 0xcc01, 0xd801, 0xf001, 0xa001];
  let crc = inicio;
  for (let i = desde; i < desde + cuantos; i++) {
    crc ^= b[i];
    for (let j = 0; j < 8; j++) {
      const bit = crc & 1;
      crc >>>= 1;
      if (bit) crc ^= tabla[j] << (7 - j);
    }
  }
  return crc & 0xffff;
}

// idioma: el de la consola (1 inglés, 5 español)
export function firmwareDS({ idioma = 1, nombre = "Player" } = {}) {
  const b = new Uint8Array(TAM);
  const v = new DataView(b.buffer);

  // Cabecera
  b.set([0x4d, 0x41, 0x43, 0x50], 0x08); // «MACP»
  b[0x1d] = 0xff; // DS normal (no Lite)
  v.setUint16(0x20, AJUSTES / 8, true);

  // La parte inalámbrica (0x2A-0x1FF)
  v.setUint16(0x2c, 0x138, true);
  b.set(MAC, 0x36);
  v.setUint16(0x3c, 0x3ffe, true); // canales
  v.setUint16(0x3e, 0xffff, true);
  b.set([2, 0x18, 0x0c, 0x01], 0x40); // tipo de RF
  CONFIG.forEach((valor, i) => v.setUint16(0x44 + i * 2, valor, true));
  b.set(BB, 0x64);
  b.set(RF, 0xce);
  b.set(RF_CANALES, 0xf2);
  b.set(BB_CANALES, 0x146);
  b.fill(0x10, 0x154, 0x154 + 14);
  b[0x162] = 0x19;
  b.fill(0xff, 0x163, 0x200);
  v.setUint16(0x2a, crc16(b, 0x2c, 0x138, 0), true);

  // Los tres puntos de acceso, sin configurar
  for (const o of PUNTOS_DE_ACCESO) {
    b[o + 0xe7] = 0xff;
    v.setUint16(o + 0xfe, crc16(b, o, 0xfe, 0), true);
  }

  // Los ajustes del usuario, dos veces (la segunda, la más nueva)
  const letras = [...nombre].slice(0, 10);
  for (let copia = 0; copia < 2; copia++) {
    const o = AJUSTES + copia * 0x100;
    v.setUint16(o, 5, true); // versión
    b[o + 0x02] = 7; // color
    b[o + 0x03] = 1; // cumpleaños: 1 de enero
    b[o + 0x04] = 1;
    letras.forEach((letra, i) => v.setUint16(o + 0x06 + i * 2, letra.charCodeAt(0), true));
    v.setUint16(o + 0x1a, letras.length, true);
    // La pantalla táctil (melonDS la vuelve a poner a su manera)
    v.setUint16(o + 0x58, 0x200, true);
    v.setUint16(o + 0x5a, 0x200, true);
    b[o + 0x5c] = 0x21;
    b[o + 0x5d] = 0x21;
    v.setUint16(o + 0x5e, 0xe00, true);
    v.setUint16(o + 0x60, 0x800, true);
    b[o + 0x62] = 0xe1;
    b[o + 0x63] = 0x81;
    v.setUint16(o + 0x64, 0xfc00 | (idioma & 7) | (3 << 4), true); // idioma y brillo
    v.setUint16(o + 0x70, copia, true);
    v.setUint16(o + 0x72, crc16(b, o, 0x70, 0xffff), true);
    b.fill(0xff, o + 0x74, o + 0x100);
  }
  return b;
}
