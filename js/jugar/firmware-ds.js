// ---------- El firmware de la DS, para melonDS ----------
//
// Sin el firmware de una DS de verdad, el núcleo melonDS de EmulatorJS se inventa uno casi vacío: sin la
// configuración inalámbrica (ni dirección MAC ni sus sumas). Los Pokémon de DS ponen en marcha la conexión
// inalámbrica al cargar la partida y, con ese firmware, fallan: «Ha habido un error de comunicación» nada más
// pulsar «Continuar». Este es uno completo, hecho como el que se inventa DeSmuME (GPL-2.0, firmware.cpp y
// wifi.cpp: los mismos valores), con la dirección MAC siempre igual (la de DeSmuME): emulador.html lo deja como
// «firmware.bin» antes de arrancar el juego, que es donde melonDS lo busca.

